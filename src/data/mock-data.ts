export function calculatePredicate(score: number, kkm: number = 75): 'A' | 'B' | 'C' | 'D' {
  const range = (100 - kkm) / 3;
  const bMin = kkm;
  const aMin = Math.round(100 - range);
  const cMin = Math.round(kkm - range);

  if (score >= aMin) return 'A';
  if (score >= bMin) return 'B';
  if (score >= cMin) return 'C';
  return 'D';
}

